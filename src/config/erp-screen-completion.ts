import type { ScreenView, ScreenInput, ScreenFieldKey } from "./erp-screen-specs";
import type { LocalizedText } from "@/lib/i18n";
const t = (en: string, ar: string): LocalizedText => ({ en, ar });
const input = (
  key: ScreenFieldKey,
  type: ScreenInput["type"] = "text",
  required = false,
): ScreenInput => ({ key, type, required });
const dates = [input("from", "date"), input("to", "date")];
const search = input("search", "search");
const status = input("status", "lookup");
const project = input("project", "lookup");
const warehouse = input("warehouse", "lookup");
const inventory = t(
  "No stock ledger, warehouse service, receipt/issue rules or valuation source is connected. These structures never create stock, availability or financial values.",
  "لا يوجد دفتر مخزون أو خدمة مستودعات أو قواعد استلام وصرف أو مصدر تقييم متصل؛ لا تنشئ هذه الهياكل مخزوناً أو إتاحة أو قيماً مالية.",
);
const cheque = t(
  "No cheque custody, maturity, deposit, clearing, endorsement or exception service is connected. No settlement, bank balance or cheque state is inferred from payment fixtures.",
  "لا توجد خدمة عهدة شيكات أو استحقاق أو إيداع أو تحصيل أو تظهير أو استثناءات متصلة؛ لا تُستنتج تسوية أو أرصدة بنكية أو حالة شيك من عينات السداد.",
);
const quality = t(
  "Requires approved checklists, project/material authority and timestamped inspection evidence. No compliance, material acceptance, corrective action or quality approval is recorded.",
  "يتطلب قوائم فحص معتمدة وصلاحية المشروع والمواد وأدلة معاينة مؤرخة؛ لا يُسجل امتثال أو قبول مواد أو إجراء تصحيحي أو اعتماد جودة.",
);
const reporting = t(
  "Report structure only: authorized records, period rules and report computation are not connected. No totals, exports, official statement or provider result is generated.",
  "هيكل تقرير فقط: السجلات المفوضة وقواعد الفترات وحساب التقرير غير متصلة؛ لا تُنشأ إجماليات أو صادرات أو قائمة رسمية أو نتيجة مزود.",
);
function spec(
  id: string,
  en: string,
  ar: string,
  columns: ScreenFieldKey[],
  filters: ScreenInput[],
  dependency: LocalizedText,
  options: Partial<ScreenView> = {},
): ScreenView[] {
  return [
    {
      id,
      title: t(en, ar),
      evidence: "adapted",
      columns,
      filters,
      dependency,
      actions: [],
      draft: [],
      ...options,
    },
  ];
}
