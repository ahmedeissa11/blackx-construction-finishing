export function statusBadgeClass(status: string): string {
  switch (status) {
    case "new":
    case "open":
    case "sent":
      return "badge badge-new";
    case "in_progress":
    case "contacted":
    case "inspection_scheduled":
    case "pending":
    case "review_requested":
    case "draft":
    case "current":
      return "badge badge-progress";
    case "completed":
    case "complete":
    case "done":
    case "approved":
    case "resolved":
    case "handed_over":
    case "signed":
    case "inspection_done":
    case "quotation_sent":
      return "badge badge-done";
    case "cancelled":
    case "blocked":
    case "terminal":
      return "badge badge-urgent";
    default:
      return "badge badge-neutral";
  }
}
